// UI acceptance in actual WebView2, writing only a disposable Chrome profile.
import { expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { environment, evidence, fixtureRoot, launch, launchChrome, pair, cleanCredentials, until, ensure } from './native-driver.mjs';
const runId = randomUUID().slice(0, 8);
const report = { runId, startedAt: new Date().toISOString(), controls: [], errors: [] };
let app, chrome, fixture;
let stage = 'prepare';
const pass = (control, detail = {}) => { report.controls.push({ control, status: 'PASS', ...detail }); console.log(JSON.stringify({ control, status: 'PASS' })); };
const children = id => chrome.evaluate(`chrome.bookmarks.getChildren(${JSON.stringify(id)})`);
async function screenshot(name) {
  await mkdir(join(evidence, 'native-screenshots'), { recursive: true });
  await app.page.screenshot({ path: join(evidence, 'native-screenshots', `${runId}-${name}.png`) });
}
try {
  report.environment = await environment();
  report.isolationRoot = await fixtureRoot();
  app = await launch(report.isolationRoot); report.webview = app.webview;
  await app.resize(1100, 760);
  report.viewports = [await app.page.evaluate(() => ({ width: innerWidth, height: innerHeight, scale: devicePixelRatio }))];
  app.page.on('pageerror', () => report.errors.push('NATIVE_PAGE_ERROR'));
  chrome = await launchChrome(join(report.isolationRoot, 'chrome-ui')); report.chrome = chrome.version;
  fixture = await chrome.evaluate(`(async()=>{const roots=await chrome.bookmarks.getTree();const bar=roots[0].children.find(n=>n.folderType==='bookmarks-bar');const empty=await chrome.bookmarks.create({parentId:bar.id,title:'R04 空目录'});const target=await chrome.bookmarks.create({parentId:bar.id,title:'R04 归档目录'});const old=await chrome.bookmarks.create({parentId:bar.id,title:'R04 旧书签',url:'https://example.invalid/old'});return {bar:bar.id,barTitle:bar.title,empty:empty.id,target:target.id,old:old.id};})()`);
  fixture.deepTitle = await chrome.evaluate(`(async()=>{let parentId=${JSON.stringify(fixture.bar)};let title='';for(let depth=1;depth<=20;depth++){title='R04 第'+depth+'层 很长的中文目录名称用于验证完整路径滚动与键盘焦点';parentId=(await chrome.bookmarks.create({parentId,title})).id;}await chrome.bookmarks.create({parentId,title:'R04 深层条目',url:'https://example.invalid/deep'});return title;})()`);
  const profileId = await pair(app, chrome, 'R04 UI 临时资料');
  const page = app.page;
  const list = () => page.getByRole('listbox', { name: '书签列表', exact: true });
  stage = 'blank-create';
  await page.locator('#library-search').fill('R04 旧书签');
  await page.getByRole('listbox', { name: '搜索结果', exact: true }).getByRole('option').filter({ hasText: 'R04 旧书签' }).click();
  await expect(page.locator('#edit-title')).toHaveValue('R04 旧书签');
  await page.getByRole('button', { name: '关闭详情，返回列表', exact: true }).click();
  await page.locator('#library-search').fill('');
  await list().getByRole('option').filter({ hasText: fixture.barTitle }).dblclick();
  await list().getByRole('option').filter({ hasText: 'R04 空目录' }).dblclick();
  await expect(page.getByText('此文件夹没有书签。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await expect(page.locator('#edit-title')).toHaveValue('');
  await expect(page.locator('#edit-url')).toHaveValue('');
  await page.locator('#edit-title').fill('R04 新书签');
  await page.locator('#edit-url').fill('https://example.invalid/new');
  await page.getByRole('button', { name: '预览新书签', exact: true }).click();
  const review = () => page.getByRole('dialog', { name: '确认变更', exact: true });
  await expect(review()).toBeVisible();
  await screenshot('new-bookmark-review');
  await review().getByRole('button', { name: '取消', exact: true }).click();
  ensure((await children(fixture.empty)).length === 0, 'CANCEL_PREVIEW_WROTE_CHROME');
  const types = page.locator('[aria-label="新建类型"]');
  await types.getByRole('button', { name: '文件夹', exact: true }).click();
  await expect(page.locator('#edit-title')).toHaveValue('');
  await expect(page.locator('#edit-url')).toHaveCount(0);
  await page.locator('#edit-title').fill('R04 新文件夹');
  await types.getByRole('button', { name: '书签', exact: true }).click();
  await expect(page.locator('#edit-title')).toHaveValue('R04 新书签');
  await expect(page.locator('#edit-url')).toHaveValue('https://example.invalid/new');
  pass('empty_folder_blank_creation_separate_drafts_and_cancel_zero_write');
  stage = 'ui-create';
  await page.getByRole('button', { name: '预览新书签', exact: true }).click();
  await review().getByRole('button', { name: '确认变更', exact: true }).click();
  await until(async () => (await children(fixture.empty)).some(node => node.title === 'R04 新书签'), 'BOOKMARK_NOT_CREATED');
  await types.getByRole('button', { name: '文件夹', exact: true }).click();
  await page.getByRole('button', { name: '预览新文件夹', exact: true }).click();
  await review().getByRole('button', { name: '确认变更', exact: true }).click();
  await until(async () => (await children(fixture.empty)).some(node => node.title === 'R04 新文件夹'), 'FOLDER_NOT_CREATED');
  await page.getByRole('button', { name: '关闭详情，返回列表', exact: true }).click();
  await expect(list().getByRole('option')).toHaveCount(2);
  pass('native_ui_creates_bookmark_and_folder_in_empty_directory');
  stage = 'batch-ui';
  await list().getByRole('checkbox', { name: '选择 R04 新书签', exact: true }).check();
  await list().getByRole('checkbox', { name: '选择 R04 新文件夹', exact: true }).check();
  await page.getByRole('button', { name: '移动所选', exact: true }).click();
  const batch = page.getByRole('region', { name: '多选变更', exact: true });
  await batch.locator('.folder-picker > summary').click();
  await batch.getByLabel('搜索文件夹路径', { exact: true }).fill('R04 归档目录');
  await batch.getByRole('listbox', { name: '目标文件夹', exact: true }).getByRole('option').click();
  await batch.getByRole('button', { name: '预览批量移动', exact: true }).click();
  const batchReview = page.getByRole('dialog', { name: '确认批量变更', exact: true });
  await expect(batchReview).toContainText('含子树共 2 项');
  await expect(batchReview).toContainText('R04 归档目录');
  await screenshot('batch-review-1100');
  await app.resize(640, 480);
  report.viewports.push(await page.evaluate(() => ({ width: innerWidth, height: innerHeight, scale: devicePixelRatio })));
  await screenshot('batch-review-640');
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'SMALL_WINDOW_HORIZONTAL_OVERFLOW');
  await batchReview.getByRole('button', { name: '确认批量变更', exact: true }).click();
  await expect(batch.getByRole('heading', { name: '全部回执已确认', exact: true })).toBeVisible({ timeout: 30000 });
  ensure((await children(fixture.target)).length === 2 && (await children(fixture.empty)).length === 0, 'UI_BATCH_MOVE_TREE_MISMATCH');
  await screenshot('batch-result-640');
  pass('native_batch_path_picker_review_apply_truthful_receipts_and_small_window');
  stage = 'history-recovery';
  const record = (await app.invoke('list_operations', { profileId })).operations.find(item => item.isBatch);
  ensure(!!record, 'BATCH_HISTORY_MARKER_MISSING');
  await page.getByRole('button', { name: '关闭详情，返回列表', exact: true }).click();
  await page.locator('#library-search').fill('R04 旧书签');
  await page.getByRole('listbox', { name: '搜索结果', exact: true }).getByRole('option').filter({ hasText: 'R04 旧书签' }).click();
  await page.getByRole('button', { name: '操作历史', exact: true }).click();
  await page.locator('.edit-history li').filter({ hasText: record.operationId }).getByRole('button', { name: '查看逐项回执', exact: true }).click();
  await expect(page.getByRole('region', { name: '逐项回执', exact: true })).toContainText('已执行 2 / 2 项');
  await screenshot('history-recovered-640');
  pass('close_detail_and_select_other_node_then_recover_batch_from_history');
  stage = 'long-path';
  await page.getByRole('navigation', { name: '主导航', exact: true }).getByRole('button', { name: '书签', exact: true }).click();
  await page.getByRole('button', { name: '关闭详情，返回列表', exact: true }).click();
  await page.locator('#library-search').fill(fixture.deepTitle);
  await page.getByRole('listbox', { name: '搜索结果', exact: true }).getByRole('option').filter({ hasText: fixture.deepTitle }).dblclick();
  const row = list().getByRole('option').filter({ hasText: 'R04 深层条目' });
  const rowBefore = await row.boundingBox();
  await row.click({ modifiers: ['Control'] });
  report.longPathGeometry = { before: rowBefore, after: await row.boundingBox(), headings: await page.locator('.browse-heading, .selection-toolbar').evaluateAll(nodes => nodes.map(node => ({ className: node.className, height: node.getBoundingClientRect().height, scrollHeight: node.scrollHeight }))) };
  ensure(Math.abs((await row.boundingBox()).y - rowBefore.y) < 1, 'SELECTION_MOVED_ROW');
  const path = page.getByLabel('查看当前目录完整路径');
  await path.click();
  const completePath = page.locator('.selection-path > p');
  await expect(completePath).toContainText('第1层');
  await expect(completePath).toContainText('第20层');
  const bounds = await completePath.boundingBox();
  ensure(bounds.y + bounds.height < 480, 'PATH_OUTSIDE_SHORT_WINDOW');
  ensure(await completePath.evaluate(node => node.scrollHeight > node.clientHeight), 'LONG_PATH_NOT_SCROLLABLE');
  await completePath.focus();
  await page.keyboard.press('End');
  await until(() => completePath.evaluate(node => node.scrollTop > 0), 'PATH_KEYBOARD_SCROLL_FAILED');
  await screenshot('long-path-640');
  await page.keyboard.press('Escape');
  await expect(path).toBeFocused();
  await expect(completePath).toBeHidden();
  await page.getByRole('button', { name: '取消选择', exact: true }).click();
  ensure(Math.abs((await row.boundingBox()).y - rowBefore.y) < 1, 'CANCEL_SELECTION_MOVED_ROW');
  pass('native_twenty_level_long_chinese_path_scroll_focus_escape_and_stable_rows');
  ensure(report.errors.length === 0, 'PAGE_ERRORS');
  report.status = 'PASS';
} catch (error) {
  report.status = 'FAIL'; report.failedStage = stage;
  report.failureCode = /^[A-Z][A-Z0-9_:.-]+$/.test(error.message) ? error.message : 'NATIVE_ASSERTION_OR_ACTION_FAILED';
  if (app) await screenshot('failure').catch(() => {});
  process.exitCode = 1;
} finally {
  if (app) { try { await cleanCredentials(app); report.temporaryCredentialsRemoved = true; } catch { report.temporaryCredentialsRemoved = false; report.status = 'FAIL'; process.exitCode = 1; } }
  if (chrome) await chrome.close();
  if (app) await app.close();
  report.finishedAt = new Date().toISOString();
  await writeFile(join(evidence, `native-editing-${runId}.json`), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ status: report.status, controls: report.controls.length, failedStage: report.failedStage, failureCode: report.failureCode, temporaryCredentialsRemoved: report.temporaryCredentialsRemoved }));
}
